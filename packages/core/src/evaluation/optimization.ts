import { z } from "zod";
import { EvalCaseSchema, VerificationStatusSchema } from "../contracts.js";

export const PromptCandidateSchema = z.object({
  id: z.string().min(1),
  dimension: z.enum(["baseline", "verification_emphasis", "reasoning_structure"]),
  promptSpecId: z.string().min(1),
  semanticPrompt: z.string().min(1),
  promptHash: z.string().regex(/^[a-f0-9]{64}$/),
  changeLog: z.array(z.string().min(1)).min(1),
});

/**
 * Execution metadata is part of promotion evidence, not an informational
 * annotation. A score without a declared runner, immutable run identifier,
 * timestamp, and observable rationale cannot establish what was actually
 * measured or be compared safely with another candidate's score.
 */
export const CandidateEvaluationProvenanceSchema = z.object({
  /** The integration or adapter that made the model call, e.g. "codex". */
  backendId: z.string().trim().min(1),
  /** The concrete executor identity, e.g. "codex-cli-structured-v1". */
  runnerId: z.string().trim().min(1),
  /** The model identity supplied to that executor, not merely a provider name. */
  modelId: z.string().trim().min(1),
  /** A UUID generated by the trusted execution boundary for this evaluation run. */
  runId: z.string().uuid(),
  /** When the trusted execution boundary recorded the result. */
  evaluatedAt: z.iso.datetime(),
  /** Concise, observable pass/fail evidence; never hidden reasoning. */
  observableEvidence: z.array(z.string().trim().min(1)).min(1),
});

export interface CandidateEvaluationProvenance {
  readonly backendId: string;
  readonly runnerId: string;
  readonly modelId: string;
  readonly runId: string;
  readonly evaluatedAt: string;
  readonly observableEvidence: readonly string[];
}

export const CandidateEvaluationRunSchema = z.object({
  candidateId: z.string().min(1),
  /** Exact rendered target and prompt digest make promotion evidence auditable. */
  targetId: z.string().min(1),
  promptHash: z.string().regex(/^[a-f0-9]{64}$/),
  caseId: z.string().min(1),
  repetition: z.number().int().nonnegative(),
  score: z.number().min(0).max(1),
  passed: z.boolean(),
  criticalRegression: z.boolean(),
  latencyMs: z.number().nonnegative(),
  inputTokens: z.number().int().nonnegative().optional(),
  outputTokens: z.number().int().nonnegative().optional(),
  cost: z.number().nonnegative().optional(),
  provenance: CandidateEvaluationProvenanceSchema,
});

export interface CandidateEvaluationRun {
  readonly candidateId: string;
  readonly targetId: string;
  readonly promptHash: string;
  readonly caseId: string;
  readonly repetition: number;
  readonly score: number;
  readonly passed: boolean;
  readonly criticalRegression: boolean;
  readonly latencyMs: number;
  readonly inputTokens?: number;
  readonly outputTokens?: number;
  readonly cost?: number;
  readonly provenance: CandidateEvaluationProvenance;
}

function toCandidateEvaluationRuns(
  runs: readonly z.infer<typeof CandidateEvaluationRunSchema>[],
): CandidateEvaluationRun[] {
  return runs.map((run) => ({
    candidateId: run.candidateId,
    targetId: run.targetId,
    promptHash: run.promptHash,
    caseId: run.caseId,
    repetition: run.repetition,
    score: run.score,
    passed: run.passed,
    criticalRegression: run.criticalRegression,
    latencyMs: run.latencyMs,
    ...(run.inputTokens === undefined ? {} : { inputTokens: run.inputTokens }),
    ...(run.outputTokens === undefined ? {} : { outputTokens: run.outputTokens }),
    ...(run.cost === undefined ? {} : { cost: run.cost }),
    provenance: {
      backendId: run.provenance.backendId,
      runnerId: run.provenance.runnerId,
      modelId: run.provenance.modelId,
      runId: run.provenance.runId,
      evaluatedAt: run.provenance.evaluatedAt,
      observableEvidence: [...run.provenance.observableEvidence],
    },
  }));
}

export const BlindedComparisonSchema = z.object({
  caseId: z.string().min(1),
  leftCandidateId: z.string().min(1),
  rightCandidateId: z.string().min(1),
  winnerCandidateId: z.string().min(1).nullable(),
});

export interface BlindedComparison {
  readonly caseId: string;
  readonly leftCandidateId: string;
  readonly rightCandidateId: string;
  readonly winnerCandidateId: string | null;
}

export interface SelectBestCandidateOptions {
  readonly baselineCandidateId: string;
  readonly minimumImprovement?: number;
  readonly comparisons?: readonly BlindedComparison[];
}

export interface CandidateSummary {
  readonly candidateId: string;
  readonly meanScore: number;
  readonly passRate: number;
  readonly meanLatencyMs: number;
  readonly totalInputTokens: number | null;
  readonly totalOutputTokens: number | null;
  readonly totalCost: number | null;
  readonly criticalRegressions: number;
}

export interface BestCandidateReport {
  readonly promoted: boolean;
  readonly selectedCandidateId: string;
  readonly baselineCandidateId: string;
  readonly measuredImprovement: number;
  readonly reason: string;
  readonly summaries: readonly CandidateSummary[];
}

export const CandidateSummarySchema = z.object({
  candidateId: z.string().min(1),
  meanScore: z.number().min(0).max(1),
  passRate: z.number().min(0).max(1),
  meanLatencyMs: z.number().nonnegative(),
  totalInputTokens: z.number().int().nonnegative().nullable(),
  totalOutputTokens: z.number().int().nonnegative().nullable(),
  totalCost: z.number().nonnegative().nullable(),
  criticalRegressions: z.number().int().nonnegative(),
});

export const BestCandidateReportSchema = z.object({
  promoted: z.boolean(),
  selectedCandidateId: z.string().min(1),
  baselineCandidateId: z.string().min(1),
  measuredImprovement: z.number(),
  reason: z.string().min(1),
  summaries: z.array(CandidateSummarySchema).min(1).max(3),
});

const CandidateEvidenceContractSchema = z.object({
  runs: z.string().min(1),
  comparisons: z.string().min(1),
  promotion: z.string().min(1),
  verification: z.string().min(1),
});

const CandidateOptimizationBaseSchema = z.object({
  version: z.literal(1),
  sourcePackage: z.object({
    id: z.string().min(1),
    verification: VerificationStatusSchema,
  }),
  /** All candidates in an optimization run must answer the same frozen demand. */
  promptSpecId: z.string().min(1),
  /** A comparison is only meaningful for one named target profile/model. */
  targetId: z.string().min(1),
  baselineCandidateId: z.string().min(1),
  candidates: z.array(PromptCandidateSchema).min(1).max(3),
  heldOutCases: z.array(EvalCaseSchema).min(1),
  evidenceContract: CandidateEvidenceContractSchema,
});

type CandidateOptimizationBase = z.infer<typeof CandidateOptimizationBaseSchema>;

function addIssue(context: z.RefinementCtx, path: readonly (string | number)[], message: string): void {
  context.addIssue({ code: "custom", path: [...path], message });
}

/**
 * A plan is a claim about a particular prompt-candidate set and a particular
 * held-out suite. Keep both identities closed: otherwise an evidence file can
 * quietly omit a weak candidate or substitute an easier case.
 */
function assertOptimizationPlanScope(
  artifact: CandidateOptimizationBase,
  context: z.RefinementCtx,
): void {
  const candidateIds = artifact.candidates.map((candidate) => candidate.id);
  if (new Set(candidateIds).size !== candidateIds.length) {
    addIssue(context, ["candidates"], "Candidate IDs must be unique.");
  }
  if (!candidateIds.includes(artifact.baselineCandidateId)) {
    addIssue(
      context,
      ["baselineCandidateId"],
      "The baseline candidate must be one of the declared candidates.",
    );
  }
  if (artifact.candidates.some((candidate) => candidate.promptSpecId !== artifact.promptSpecId)) {
    addIssue(
      context,
      ["candidates"],
      "Every candidate must preserve the plan's frozen prompt specification.",
    );
  }
  if (new Set(artifact.candidates.map((candidate) => candidate.promptHash)).size !== candidateIds.length) {
    addIssue(
      context,
      ["candidates"],
      "Every candidate must have a distinct prompt hash.",
    );
  }
  const caseIds = artifact.heldOutCases.map((evalCase) => evalCase.id);
  if (new Set(caseIds).size !== caseIds.length) {
    addIssue(context, ["heldOutCases"], "Held-out evaluation case IDs must be unique.");
  }
}

/** A serializable plan with no evaluation result or promotion claim. */
export const CandidateOptimizationPlanSchema = CandidateOptimizationBaseSchema.extend({
  state: z.literal("awaiting_evidence"),
}).superRefine(assertOptimizationPlanScope);

/**
 * A serializable evidence artifact. This is intentionally separate from a
 * prompt package: a promotion recommendation cannot silently alter compiled
 * artifacts or elevate their verification status.
 */
export const CandidateOptimizationEvidenceSchema = CandidateOptimizationBaseSchema.extend({
  state: z.literal("evaluated"),
  minimumImprovement: z.number().nonnegative(),
  runs: z.array(CandidateEvaluationRunSchema).min(1),
  comparisons: z.array(BlindedComparisonSchema).optional(),
  report: BestCandidateReportSchema,
}).superRefine((artifact, context) => {
  assertOptimizationPlanScope(artifact, context);

  const candidateIds = new Set(artifact.candidates.map((candidate) => candidate.id));
  const candidateHashes = new Map(
    artifact.candidates.map((candidate) => [candidate.id, candidate.promptHash]),
  );
  const caseIds = new Set(artifact.heldOutCases.map((evalCase) => evalCase.id));
  const observedCandidateIds = new Set(artifact.runs.map((run) => run.candidateId));
  const observedCaseIds = new Set(artifact.runs.map((run) => run.caseId));

  if (
    observedCandidateIds.size !== candidateIds.size ||
    [...observedCandidateIds].some((candidateId) => !candidateIds.has(candidateId))
  ) {
    addIssue(
      context,
      ["runs"],
      "Runs must include every declared candidate and no unknown candidate IDs.",
    );
  }
  if (
    artifact.runs.some(
      (run) =>
        run.targetId !== artifact.targetId ||
        run.promptHash !== candidateHashes.get(run.candidateId),
    )
  ) {
    addIssue(
      context,
      ["runs"],
      "Every run must name the plan target and the exact hash of its declared candidate prompt.",
    );
  }
  if (
    observedCaseIds.size !== caseIds.size ||
    [...observedCaseIds].some((caseId) => !caseIds.has(caseId))
  ) {
    addIssue(
      context,
      ["runs"],
      "Runs must cover every declared held-out case and no other cases.",
    );
  }

  const comparisons = artifact.comparisons ?? [];
  if (
    comparisons.some(
      (comparison) =>
        !caseIds.has(comparison.caseId) ||
        !candidateIds.has(comparison.leftCandidateId) ||
        !candidateIds.has(comparison.rightCandidateId) ||
        comparison.leftCandidateId === comparison.rightCandidateId ||
        (comparison.winnerCandidateId !== null && !candidateIds.has(comparison.winnerCandidateId)),
    )
  ) {
    addIssue(
      context,
      ["comparisons"],
      "Comparisons may reference only distinct declared candidates and held-out cases.",
    );
  }

  try {
    const recomputed = selectBestTestedCandidate(toCandidateEvaluationRuns(artifact.runs), {
      baselineCandidateId: artifact.baselineCandidateId,
      minimumImprovement: artifact.minimumImprovement,
      ...(comparisons.length === 0 ? {} : { comparisons }),
    });
    if (canonicalJson(recomputed) !== canonicalJson(artifact.report)) {
      addIssue(
        context,
        ["report"],
        "Promotion report does not match the supplied, scoped evaluation evidence.",
      );
    }
  } catch (error) {
    addIssue(
      context,
      ["runs"],
      `Candidate evidence does not satisfy the promotion gate: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
});

function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  const record = value as Record<string, unknown>;
  return `{${Object.keys(record)
    .sort()
    .map((key) => `${JSON.stringify(key)}:${canonicalJson(record[key])}`)
    .join(",")}}`;
}

function average(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0) / values.length;
}

function optionalTotal(
  runs: readonly CandidateEvaluationRun[],
  field: "inputTokens" | "outputTokens" | "cost",
): number | null {
  const values = runs.map((run) => run[field]);
  return values.every((value): value is number => value !== undefined)
    ? values.reduce((total, value) => total + value, 0)
    : null;
}

function runKey(run: CandidateEvaluationRun): string {
  return `${run.caseId}\u0000${String(run.repetition)}`;
}

function isSha256(value: string): boolean {
  return /^[a-f0-9]{64}$/u.test(value);
}

/**
 * Candidate scores are only comparable when they came from one target and
 * each candidate's runs identify one immutable prompt. This protects direct
 * library callers as well as serialized evidence artifacts.
 */
function assertComparableEvaluationSubjects(
  grouped: ReadonlyMap<string, readonly CandidateEvaluationRun[]>,
): void {
  const targetIds = new Set<string>();
  const backendIds = new Set<string>();
  const runnerIds = new Set<string>();
  const modelIds = new Set<string>();
  for (const [candidateId, candidateRuns] of grouped) {
    const promptHashes = new Set<string>();
    for (const run of candidateRuns) {
      if (run.targetId.trim().length === 0 || !isSha256(run.promptHash)) {
        throw new Error("Candidate evaluation runs must include a target ID and SHA-256 prompt hash.");
      }
      targetIds.add(run.targetId);
      promptHashes.add(run.promptHash);
      const provenance = CandidateEvaluationProvenanceSchema.safeParse(run.provenance);
      if (!provenance.success) {
        throw new Error(
          "Candidate evaluation runs must declare auditable backend, runner, model, run, timestamp, and observable evidence provenance.",
        );
      }
      backendIds.add(provenance.data.backendId);
      runnerIds.add(provenance.data.runnerId);
      modelIds.add(provenance.data.modelId);
    }
    if (promptHashes.size !== 1) {
      throw new Error(`Candidate ${candidateId} was evaluated with more than one prompt hash.`);
    }
  }
  if (targetIds.size !== 1) {
    throw new Error("Candidate promotion requires all runs to use one identical target.");
  }
  if (backendIds.size !== 1 || runnerIds.size !== 1 || modelIds.size !== 1) {
    throw new Error(
      "Candidate promotion requires all runs to declare one identical backend, runner, and model provenance.",
    );
  }
}

function assertIdenticalHeldOutRuns(
  grouped: ReadonlyMap<string, readonly CandidateEvaluationRun[]>,
): void {
  const entries = [...grouped.entries()];
  const reference = entries[0];
  if (reference === undefined) {
    throw new Error("Candidate optimization requires evaluation runs.");
  }
  const expected = [...new Set(reference[1].map(runKey))].sort();
  if (expected.length !== reference[1].length) {
    throw new Error(`Candidate ${reference[0]} has duplicate held-out runs.`);
  }
  for (const [candidateId, runs] of entries.slice(1)) {
    const actual = [...new Set(runs.map(runKey))].sort();
    if (actual.length !== runs.length || JSON.stringify(actual) !== JSON.stringify(expected)) {
      throw new Error(
        `Candidate ${candidateId} was not evaluated on the identical held-out cases and repetitions.`,
      );
    }
  }
}

function assertReversedOrderCoverage(
  comparisons: readonly BlindedComparison[],
  candidateIds: ReadonlySet<string>,
  caseIds: ReadonlySet<string>,
): void {
  const directions = new Set(
    comparisons.map(
      (comparison) =>
        `${comparison.caseId}\u0000${comparison.leftCandidateId}\u0000${comparison.rightCandidateId}`,
    ),
  );
  if (directions.size !== comparisons.length) {
    throw new Error("Subjective comparisons contain a duplicate case/candidate order.");
  }
  for (const comparison of comparisons) {
    if (!caseIds.has(comparison.caseId)) {
      throw new Error(`Subjective comparison references unknown case ${comparison.caseId}.`);
    }
    if (
      !candidateIds.has(comparison.leftCandidateId) ||
      !candidateIds.has(comparison.rightCandidateId) ||
      comparison.leftCandidateId === comparison.rightCandidateId
    ) {
      throw new Error("Subjective comparisons must compare two distinct evaluated candidates.");
    }
    const reverse =
      `${comparison.caseId}\u0000${comparison.rightCandidateId}\u0000${comparison.leftCandidateId}`;
    if (!directions.has(reverse)) {
      throw new Error(
        `Subjective comparison for ${comparison.caseId} lacks reversed candidate order.`,
      );
    }
    if (
      comparison.winnerCandidateId !== null &&
      (comparison.winnerCandidateId !== comparison.leftCandidateId &&
        comparison.winnerCandidateId !== comparison.rightCandidateId)
    ) {
      throw new Error("A comparison winner must be one of its two candidates or null.");
    }
  }
}

/**
 * Promotes only a challenger tested on the exact same held-out runs as the
 * baseline. Pre-scored subjective trials are accepted only with reversed order
 * coverage, preventing a one-sided presentation from becoming promotion proof.
 */
export function selectBestTestedCandidate(
  runs: readonly CandidateEvaluationRun[],
  options: SelectBestCandidateOptions,
): BestCandidateReport {
  if (
    options.baselineCandidateId.trim().length === 0 ||
    (options.minimumImprovement !== undefined &&
      (!Number.isFinite(options.minimumImprovement) || options.minimumImprovement < 0))
  ) {
    throw new Error("Minimum improvement cannot be negative.");
  }
  const grouped = new Map<string, CandidateEvaluationRun[]>();
  for (const run of runs) {
    if (
      run.candidateId.trim().length === 0 ||
      run.targetId.trim().length === 0 ||
      !isSha256(run.promptHash) ||
      run.caseId.trim().length === 0 ||
      !Number.isFinite(run.score) ||
      run.score < 0 ||
      run.score > 1 ||
      !Number.isFinite(run.latencyMs) ||
      run.latencyMs < 0 ||
      !Number.isInteger(run.repetition) ||
      run.repetition < 0 ||
      (run.inputTokens !== undefined &&
        (!Number.isFinite(run.inputTokens) || !Number.isInteger(run.inputTokens) || run.inputTokens < 0)) ||
      (run.outputTokens !== undefined &&
        (!Number.isFinite(run.outputTokens) || !Number.isInteger(run.outputTokens) || run.outputTokens < 0)) ||
      (run.cost !== undefined && (!Number.isFinite(run.cost) || run.cost < 0))
    ) {
      throw new Error("Candidate evaluation runs contain an invalid score, duration, or repetition.");
    }
    grouped.set(run.candidateId, [...(grouped.get(run.candidateId) ?? []), run]);
  }
  if (grouped.size === 0 || grouped.size > 3) {
    throw new Error("Candidate optimization requires between one and three candidates.");
  }
  if (!grouped.has(options.baselineCandidateId)) {
    throw new Error("The baseline candidate has no evaluation runs.");
  }
  assertComparableEvaluationSubjects(grouped);
  assertIdenticalHeldOutRuns(grouped);
  assertReversedOrderCoverage(
    options.comparisons ?? [],
    new Set(grouped.keys()),
    new Set(runs.map((run) => run.caseId)),
  );

  const summaries = [...grouped.entries()].map(([candidateId, candidateRuns]) => ({
    candidateId,
    meanScore: average(candidateRuns.map((run) => run.score)),
    passRate: candidateRuns.filter((run) => run.passed).length / candidateRuns.length,
    meanLatencyMs: average(candidateRuns.map((run) => run.latencyMs)),
    totalInputTokens: optionalTotal(candidateRuns, "inputTokens"),
    totalOutputTokens: optionalTotal(candidateRuns, "outputTokens"),
    totalCost: optionalTotal(candidateRuns, "cost"),
    criticalRegressions: candidateRuns.filter((run) => run.criticalRegression).length,
  }));
  const baseline = summaries.find(
    (summary) => summary.candidateId === options.baselineCandidateId,
  );
  if (baseline === undefined) throw new Error("The baseline summary is unavailable.");
  const eligible = summaries
    .filter(
      (summary) =>
        summary.criticalRegressions === 0 &&
        summary.passRate === 1 &&
        summary.passRate >= baseline.passRate,
    )
    .sort(
      (left, right) =>
        right.meanScore - left.meanScore ||
        right.passRate - left.passRate ||
        left.meanLatencyMs - right.meanLatencyMs ||
        left.candidateId.localeCompare(right.candidateId),
    );
  const best = eligible[0] ?? baseline;
  const measuredImprovement = best.meanScore - baseline.meanScore;
  const minimumImprovement = options.minimumImprovement ?? 0;
  const promoted =
    best.candidateId !== baseline.candidateId &&
    measuredImprovement > minimumImprovement;

  return {
    promoted,
    selectedCandidateId: promoted ? best.candidateId : baseline.candidateId,
    baselineCandidateId: baseline.candidateId,
    measuredImprovement,
    reason: promoted
      ? "Challenger improved the identical held-out suite with no critical regression."
      : "No challenger cleared the measurable-improvement and critical-regression gate.",
    summaries,
  };
}
